// Writes games/catalog.js: each game's name, cover, rules and lobby options, plus a loader for its code.
// The site shows the home page and lobby from the catalog and downloads a game only when it is played.
// The catalog also carries VERSION (when and from what the site was built) so players can tell when
// someone's copy is out of date, and FILES (what to refresh when updating).
//   node tools/build-catalog.mjs          rebuild (tools/test.mjs runs this for you)
//   node tools/build-catalog.mjs --check  fail if the catalog is out of date (used on GitHub)
import fs from 'node:fs';
import crypto from 'node:crypto';
import { GAMES } from '../games/index.js';

const root = new URL('../', import.meta.url);
const OUT = new URL('games/catalog.js', root);
const list = (dir, ext) => fs.readdirSync(new URL(dir, root)).filter((f) => ext.test(f)).map((f) => dir + f).sort();
const FILES = ['index.html', 'css/style.css', ...list('js/', /\.js$/), ...list('games/', /\.js$/).filter((f) => f !== 'games/catalog.js')];

// Covers are shown as pre-rendered images (tools/build-covers.mjs) when one matches the current art;
// otherwise the live illustration is used, and --check fails so the images get rebuilt.
const coverHash = (svg) => crypto.createHash('sha256').update(String(svg).replace(/\r\n/g, '\n')).digest('hex').slice(0, 10);
const manifestUrl = new URL('covers/manifest.json', root);
const covers = fs.existsSync(manifestUrl) ? JSON.parse(fs.readFileSync(manifestUrl, 'utf8')) : {};
const staleCovers = [];
const coverOf = (g) => {
  const c = covers[g.id];
  if (c && c.hash === coverHash(g.cover) && fs.existsSync(new URL('covers/' + c.file, root))) {
    return `<img class="cover-img" src="covers/${c.file}" alt="" width="${c.width}" height="${c.height}" decoding="async" loading="lazy">`;
  }
  if (g.cover) staleCovers.push(g.id);
  return g.cover;
};
const entries = GAMES.map((g) => ({
  id: g.id, name: g.name, description: g.description, minPlayers: g.minPlayers, maxPlayers: g.maxPlayers,
  cover: coverOf(g), howTo: g.howTo, options: g.options,
  // Flags the lobby needs before the game's code has loaded.
  bot: !!g.bot, onTimeout: !!g.onTimeout, defaultTimer: g.defaultTimer, simultaneous: !!g.simultaneous, keepDom: !!g.keepDom,
  // Live games (characters moving in a shared world): seats open mid-game, one player per device,
  // and nothing kept on the device except what players save themselves.
  ...(g.live ? { live: true, dropIn: !!g.dropIn, soloOnDevice: !!g.soloOnDevice, manualSave: !!g.manualSave } : {}),
}));
const hash = crypto.createHash('sha256');
for (const f of FILES) hash.update(f + '\0' + fs.readFileSync(new URL(f, root), 'utf8').replace(/\r\n/g, '\n'));
hash.update(JSON.stringify(entries));
const digest = hash.digest('hex').slice(0, 10);

// Keep the old timestamp when nothing changed, so rebuilding is a no-op.
const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').match(/VERSION = '(\d{12})-(\w+)'/) : null;
const stamp = old && old[2] === digest ? old[1] : new Date().toISOString().replace(/\D/g, '').slice(0, 12);
const text = `// Generated by node tools/build-catalog.mjs. Do not edit: change the game files and rebuild.
// Names, covers and rules for the home page and lobby; each game's code loads only when it is played.

export const VERSION = '${stamp}-${digest}';
export const FILES = ${JSON.stringify(FILES)};
export const CATALOG = ${JSON.stringify(entries, null, 1)};
export const loaders = {
${GAMES.map((g) => `  ${g.id}: () => import('./${g.id}.js'),`).join('\n')}
};
`;
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
if (staleCovers.length) console.warn(`Cover images out of date for: ${staleCovers.join(', ')}. Run node tools/build-covers.mjs (they show as live illustrations until then).`);
if (process.argv.includes('--check')) {
  if (staleCovers.length) { console.error('Cover images are out of date: run node tools/build-covers.mjs, then node tools/build-catalog.mjs, and commit both.'); process.exit(1); }
  if (current !== text) { console.error('games/catalog.js is out of date: run node tools/build-catalog.mjs and commit it.'); process.exit(1); }
  console.log(`Catalog is up to date (${VERSION_LINE()}).`);
} else if (current !== text) {
  fs.writeFileSync(OUT, text);
  console.log(`Catalog rebuilt: version ${stamp}-${digest}, ${entries.length} games, ${Math.round(text.length / 1024)} KB.`);
} else console.log(`Catalog is up to date (${VERSION_LINE()}).`);
function VERSION_LINE() { return `version ${stamp}-${digest}`; }
